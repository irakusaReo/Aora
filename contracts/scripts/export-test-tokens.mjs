// Exports the runtime code of the TEST-ONLY tokens for the API's local-chain
// tests (phase-5 plan P5-2). Run `forge build` first. The output is a
// generated, version-controlled artifact (ADR 0006); CI checks it is current.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
const artifact = (name) =>
  JSON.parse(readFileSync(resolve(root, `out/TestToken.sol/${name}.json`), 'utf8'));
const out = {
  note: 'Generated by contracts/scripts/export-test-tokens.mjs. TEST ONLY: local chain, never deployed.',
  TestUsdc: artifact('TestUsdc').deployedBytecode.object,
  TestOtherToken: artifact('TestOtherToken').deployedBytecode.object,
};
writeFileSync(
  resolve(root, '../services/api/test/support/test-tokens.json'),
  `${JSON.stringify(out, null, 2)}\n`,
);

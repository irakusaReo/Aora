// Exports the ABIs of AORA's contracts to the API as generated,
// version-controlled TypeScript (ADR 0006, ADR 0015 rule 8). Run `forge build`
// first. CI checks the output is current.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';

const root = resolve(import.meta.dirname, '..');
for (const [name, constant] of [
  ['NamUsdcVault', 'namUsdcVaultAbi'],
  ['AnchorRegistry', 'anchorRegistryAbi'],
]) {
  const { abi } = JSON.parse(readFileSync(resolve(root, `out/${name}.sol/${name}.json`), 'utf8'));
  const body = [
    `// Generated by contracts/scripts/export-abis.mjs from contracts/src/${name}.sol. Do not edit.`,
    `export const ${constant} = ${JSON.stringify(abi, null, 2)} as const;`,
    '',
  ].join('\n');
  writeFileSync(resolve(root, `../services/api/src/modules/chain/abi/${name}.ts`), body);
}
